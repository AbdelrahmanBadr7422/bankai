CREATE TABLE orders
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number        VARCHAR(30)    NOT NULL,
    user_id             BIGINT         NOT NULL REFERENCES users (id),
    status              VARCHAR(20)    NOT NULL,
    subtotal            NUMERIC(12, 2) NOT NULL,
    shipping_fee        NUMERIC(12, 2) NOT NULL,
    total               NUMERIC(12, 2) NOT NULL,
    ship_recipient_name VARCHAR(120)   NOT NULL,
    ship_phone          VARCHAR(30)    NOT NULL,
    ship_line1          VARCHAR(255)   NOT NULL,
    ship_line2          VARCHAR(255),
    ship_city           VARCHAR(100)   NOT NULL,
    ship_postal_code    VARCHAR(20)    NOT NULL,
    ship_country        VARCHAR(100)   NOT NULL,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_orders_number UNIQUE (order_number),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND shipping_fee >= 0 AND total >= 0)
);

CREATE INDEX idx_orders_user ON orders (user_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_created ON orders (created_at DESC);

CREATE TABLE order_items
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id    BIGINT         NOT NULL REFERENCES products (id),
    product_title VARCHAR(255)   NOT NULL,
    unit_price    NUMERIC(10, 2) NOT NULL,
    quantity      INTEGER        NOT NULL,
    line_total    NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);

CREATE TABLE payments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method     VARCHAR(20)    NOT NULL,
    status     VARCHAR(20)    NOT NULL,
    amount     NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    paid_at    TIMESTAMPTZ,
    CONSTRAINT uq_payments_order UNIQUE (order_id),
    CONSTRAINT ck_payments_method CHECK (method IN ('COD')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'PAID', 'CANCELLED'))
);